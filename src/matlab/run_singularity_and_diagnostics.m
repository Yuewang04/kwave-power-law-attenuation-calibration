function run_singularity_and_diagnostics(results_dir)
%RUN_SINGULARITY_AND_DIAGNOSTICS Generate all diagnostic, scaling, grid, worked-example, and fitPowerLawParams datasets.
%   Eliminates all previously unscripted JSON artifacts so 100% of repository
%   results are end-to-end reproducible from committed MATLAB code.

if nargin < 1 || isempty(results_dir)
    root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    results_dir = fullfile(root, 'results');
end
if ~isfolder(results_dir), mkdir(results_dir); end

np2db = 20 * log10(exp(1));
f0 = 0.5;
c_base = 3100;
rho_base = 2200;
alpha_lit = 21.5 * np2db / 100;
target_f0 = alpha_lit * f0;

% =========================================================================
% 1. Fine singularity scan across y in [0.75, 1.35] at 0.5 MHz
% =========================================================================
fprintf('--- [1/6] Running fine near-y=1 singularity scan ---\n');
y_scan = [0.75, 0.78, 0.80, 0.85, 0.90, 0.95, 0.97, 0.98, 0.984, 0.99, ...
          1.01, 1.02, 1.05, 1.10, 1.15, 1.20, 1.25, 1.30, 1.32, 1.35];
scan_items = cell(1, numel(y_scan));
for i = 1:numel(y_scan)
    yv = y_scan(i);
    coeff = alpha_lit * (f0 ^ (1 - yv));
    one = run_one_kwave_case(f0, coeff, yv, '', 1, c_base, rho_base);
    if strcmp(one.field_status, 'stable')
        rel_err = 100 * (one.attenuation_dB_cm - target_f0) / target_f0;
    else
        rel_err = NaN;
    end
    if isfinite(one.analytical_pde_attenuation_dB_cm)
        ana_err = 100 * (one.analytical_pde_attenuation_dB_cm - target_f0) / target_f0;
    else
        ana_err = NaN;
    end
    scan_items{i} = struct( ...
        'y', yv, ...
        'alpha_coeff', coeff, ...
        'field_status', one.field_status, ...
        'max_abs_pressure_Pa', one.max_abs_pressure_Pa, ...
        'p_max_pos', one.p_max_pos, ...
        'p_min_neg', one.p_min_neg, ...
        'attenuation_dB_cm', one.attenuation_dB_cm, ...
        'target_dB_cm', target_f0, ...
        'relative_error_percent', rel_err, ...
        'analytical_pde_attenuation_dB_cm', one.analytical_pde_attenuation_dB_cm, ...
        'analytical_pde_error_percent', ana_err, ...
        'measured_phase_speed_m_s', one.measured_phase_speed_m_s, ...
        'analytical_phase_speed_m_s', one.analytical_phase_speed_m_s, ...
        'stiffness_M_k0', one.stiffness_M_k0, ...
        'treeby_denominator', one.treeby_denominator, ...
        'fit_R2', one.fit_R2, ...
        'distances_m', one.distances_m, ...
        'ln_p_max', one.ln_p_max, ...
        'fit_residual', one.fit_residual);
end
write_json_pretty(fullfile(results_dir, 'singularity_scan.json'), [scan_items{:}]);

% =========================================================================
% 2. Nonlinear denominator scaling check (0.5x, 1x, 2x) at y=1.05 AND y=2.0
% =========================================================================
fprintf('--- [2/6] Running alpha_coeff scaling check (y=1.05 vs y=2.0) ---\n');
scales = [0.5, 1.0, 2.0];
cases_105 = cell(1, numel(scales));
cases_200 = cell(1, numel(scales));
for k = 1:numel(scales)
    sc = scales(k);
    % y = 1.05
    y105 = 1.05;
    c105 = alpha_lit * (f0 ^ (1 - y105)) * sc;
    r105 = run_one_kwave_case(f0, c105, y105, '', 1, c_base, rho_base);
    exp105 = c105 * (f0 ^ y105);
    cases_105{k} = struct( ...
        'coeff_scale', sc, ...
        'alpha_coeff', c105, ...
        'measured_dB_cm', r105.attenuation_dB_cm, ...
        'expected_dB_cm', exp105, ...
        'analytical_pde_dB_cm', r105.analytical_pde_attenuation_dB_cm, ...
        'relative_error_vs_powerlaw_percent', 100 * (r105.attenuation_dB_cm - exp105) / exp105, ...
        'analytical_pde_error_vs_powerlaw_percent', 100 * (r105.analytical_pde_attenuation_dB_cm - exp105) / exp105, ...
        'relative_error_vs_analytical_pde_percent', 100 * (r105.attenuation_dB_cm - r105.analytical_pde_attenuation_dB_cm) / r105.analytical_pde_attenuation_dB_cm, ...
        'measured_phase_speed_m_s', r105.measured_phase_speed_m_s, ...
        'analytical_phase_speed_m_s', r105.analytical_phase_speed_m_s, ...
        'treeby_denominator', r105.treeby_denominator, ...
        'fit_R2', r105.fit_R2);

    % y = 2.0 control (tan(pi) = 0 -> exact linear proportionality with alpha_coeff)
    y200 = 2.0;
    c200 = alpha_lit * (f0 ^ (1 - y200)) * sc;
    r200 = run_one_kwave_case(f0, c200, y200, '', 1, c_base, rho_base);
    exp200 = c200 * (f0 ^ y200);
    cases_200{k} = struct( ...
        'coeff_scale', sc, ...
        'alpha_coeff', c200, ...
        'measured_dB_cm', r200.attenuation_dB_cm, ...
        'expected_dB_cm', exp200, ...
        'analytical_pde_dB_cm', r200.analytical_pde_attenuation_dB_cm, ...
        'relative_error_vs_powerlaw_percent', 100 * (r200.attenuation_dB_cm - exp200) / exp200, ...
        'measured_phase_speed_m_s', r200.measured_phase_speed_m_s, ...
        'treeby_denominator', r200.treeby_denominator, ...
        'fit_R2', r200.fit_R2);
end
scaling_out = struct( ...
    'y', 1.05, ...
    'note', 'Non-proportional scaling with alpha_coeff at y=1.05 arises directly from alpha_0 in the fractional-Laplacian dispersion denominator 1 - (y+1)*alpha_0*c_0*tan(pi*y/2)*w^(y-1), while spatial decay remains strictly exponential (R^2 > 0.99999). At y=2.0, tan(pi)=0 and scaling is strictly proportional.', ...
    'cases', [cases_105{:}], ...
    'cases_y2_control', [cases_200{:}]);
write_json_pretty(fullfile(results_dir, 'tan_scaling_check.json'), scaling_out);

% =========================================================================
% 3. Grid-refinement check (dx = 0.5, 0.25, 0.125 mm) at y=1.05
% =========================================================================
fprintf('--- [3/6] Running grid resolution check (dx = 0.5, 0.25, 0.125 mm) ---\n');
gfactors = [1, 2, 4];
gcases = cell(1, numel(gfactors));
y105 = 1.05;
c105 = alpha_lit * (f0 ^ (1 - y105));
for k = 1:numel(gfactors)
    gf = gfactors(k);
    rg = run_one_kwave_case(f0, c105, y105, '', gf, c_base, rho_base);
    gcases{k} = struct( ...
        'grid_factor', gf, ...
        'Nx', 512 * gf, ...
        'dx_mm', 0.5 / gf, ...
        'source_idx', 35 * gf, ...
        'pml_size', 20 * gf, ...
        'measured_dB_cm', rg.attenuation_dB_cm, ...
        'analytical_pde_dB_cm', rg.analytical_pde_attenuation_dB_cm, ...
        'relative_error_percent', 100 * (rg.attenuation_dB_cm - target_f0) / target_f0, ...
        'analytical_pde_error_percent', 100 * (rg.analytical_pde_attenuation_dB_cm - target_f0) / target_f0, ...
        'fit_R2', rg.fit_R2);
end
grid_out = struct('y', 1.05, 'f0_MHz', f0, 'target_dB_cm', target_f0, 'cases', [gcases{:}]);
write_json_pretty(fullfile(results_dir, 'grid_resolution_check.json'), grid_out);

% =========================================================================
% 4. Full-band no_dispersion scans for y=1.1 (Fig 6) and exact y=1.0 (Route B)
% =========================================================================
fprintf('--- [4/6] Running y=1.1 and y=1.0 full-band no_dispersion scans ---\n');
run_kwave_experiments(fullfile(results_dir, 'y11_no_dispersion.json'), 1.1, 'no_dispersion');
run_kwave_experiments(fullfile(results_dir, 'y1_no_dispersion_fullband.json'), 1.0, 'no_dispersion');

% =========================================================================
% 5. Part 3 Worked Example: pure cortical bone limit (c=2800, rho=1900, y=1.1)
% =========================================================================
fprintf('--- [5/6] Running Part 3 worked example (c=2800, rho=1900) ---\n');
c_cort = 2800;
rho_cort = 1900;
y_ex = 1.1;
coeff_ex_u = alpha_lit;
coeff_ex_c = alpha_lit * (f0 ^ (1 - y_ex));

w1 = run_one_kwave_case(f0, coeff_ex_u, y_ex, '', 1, c_cort, rho_cort);
w2 = run_one_kwave_case(f0, coeff_ex_c, y_ex, '', 1, c_cort, rho_cort);
w3 = run_one_kwave_case(f0, coeff_ex_u, y_ex, 'no_dispersion', 1, c_cort, rho_cort);
w4 = run_one_kwave_case(f0, coeff_ex_c, y_ex, 'no_dispersion', 1, c_cort, rho_cort);
w5 = run_one_kwave_case(f0, alpha_lit, 1.0, 'no_dispersion', 1, c_cort, rho_cort);
[a_fit_ex, y_fit_ex] = fitPowerLawParams(coeff_ex_c, y_ex, c_cort, 0.2e6, 1.0e6, false);
w6 = run_one_kwave_case(f0, a_fit_ex, y_fit_ex, '', 1, c_cort, rho_cort);

part3_rows = [ ...
    make_part3_row('Default dispersive, uncorrected (y=1.1)', coeff_ex_u, y_ex, w1, target_f0), ...
    make_part3_row('Default dispersive, f0-matched (y=1.1)', coeff_ex_c, y_ex, w2, target_f0), ...
    make_part3_row('no_dispersion, uncorrected (y=1.1)', coeff_ex_u, y_ex, w3, target_f0), ...
    make_part3_row('no_dispersion, f0-matched (y=1.1)', coeff_ex_c, y_ex, w4, target_f0), ...
    make_part3_row('no_dispersion, exact linear (y=1.0)', alpha_lit, 1.0, w5, target_f0), ...
    make_part3_row('Default dispersive + fitPowerLawParams (from y=1.1)', a_fit_ex, y_fit_ex, w6, target_f0)];

part3_out = struct( ...
    'sound_speed_m_s', c_cort, ...
    'density_kg_m3', rho_cort, ...
    'f0_MHz', f0, ...
    'target_dB_cm', target_f0, ...
    'rows', part3_rows);
write_json_pretty(fullfile(results_dir, 'worked_example_part3.json'), part3_out);

% =========================================================================
% 6. Audit of k-Wave built-in fitPowerLawParams across y near 1
% =========================================================================
fprintf('--- [6/6] Auditing k-Wave fitPowerLawParams near y=1 ---\n');
y_targets = [0.99, 1.00, 1.01, 1.05, 1.10, 1.50, 2.00];
fpl_cases = cell(1, numel(y_targets));
for k = 1:numel(y_targets)
    yt = y_targets(k);
    a0_des = alpha_lit * (f0 ^ (1 - yt));
    [a0_fit, y_fit] = fitPowerLawParams(a0_des, yt, c_base, 0.2e6, 1.0e6, false);
    sim_fit = run_one_kwave_case(f0, a0_fit, y_fit, '', 1, c_base, rho_base);
    if strcmp(sim_fit.field_status, 'stable')
        att_err = 100 * (sim_fit.attenuation_dB_cm - target_f0) / target_f0;
        cp_err = 100 * (sim_fit.measured_phase_speed_m_s - c_base) / c_base;
    else
        att_err = NaN;
        cp_err = NaN;
    end
    fpl_cases{k} = struct( ...
        'y_desired', yt, ...
        'a0_desired', a0_des, ...
        'a0_fit', a0_fit, ...
        'y_fit', y_fit, ...
        'field_status', sim_fit.field_status, ...
        'max_abs_pressure_Pa', sim_fit.max_abs_pressure_Pa, ...
        'simulated_attenuation_dB_cm_at_f0', sim_fit.attenuation_dB_cm, ...
        'target_dB_cm_at_f0', target_f0, ...
        'attenuation_error_percent', att_err, ...
        'measured_phase_speed_m_s', sim_fit.measured_phase_speed_m_s, ...
        'nominal_sound_speed_m_s', c_base, ...
        'phase_speed_shift_percent', cp_err, ...
        'analytical_phase_speed_m_s', sim_fit.analytical_phase_speed_m_s, ...
        'stiffness_M_k0', sim_fit.stiffness_M_k0, ...
        'fit_R2', sim_fit.fit_R2);
end
fpl_out = struct( ...
    'sound_speed_m_s', c_base, ...
    'density_kg_m3', rho_base, ...
    'f0_MHz', f0, ...
    'fit_band_Hz', [0.2e6, 1.0e6], ...
    'cases', [fpl_cases{:}]);
write_json_pretty(fullfile(results_dir, 'fit_power_law_params_audit.json'), fpl_out);
end

function row = make_part3_row(label, coeff, y, sim, target_f0)
row = struct( ...
    'label', label, ...
    'alpha_coeff', coeff, ...
    'alpha_power', y, ...
    'alpha_mode', sim.alpha_mode, ...
    'attenuation_dB_cm', sim.attenuation_dB_cm, ...
    'analytical_pde_dB_cm', sim.analytical_pde_attenuation_dB_cm, ...
    'relative_error_percent', 100 * (sim.attenuation_dB_cm - target_f0) / target_f0, ...
    'measured_phase_speed_m_s', sim.measured_phase_speed_m_s, ...
    'fit_R2', sim.fit_R2);
end

function write_json_pretty(path, val)
fid = fopen(path, 'w');
assert(fid >= 0, 'Cannot open %s', path);
cleanup_obj = onCleanup(@() fclose(fid));
fwrite(fid, jsonencode(val, 'PrettyPrint', true), 'char');
end
