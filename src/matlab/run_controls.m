function result = run_controls(output_path)
%RUN_CONTROLS Timestep-refinement and estimator controls near y=1 (y=0.98 and y=0.99).
%   Uses standard interior source (source_idx=35, PML=20) and 180-us record.
%   Tests both y=0.98 (stable anomalous regime, M(k0) > 0) and y=0.99
%   (elliptic Hadamard blow-up regime, M(k0) < 0) across dt, dt/2, and dt/4.

if nargin < 1 || isempty(output_path)
    output_path = fullfile(pwd, 'results', 'controls_y098.json');
end

np2db = 20 * log10(exp(1));
f0 = 0.5;
c = 3100;
rho = 2200;
alpha_lit = 21.5 * np2db / 100;
target_f0 = alpha_lit * f0;
dt_factors = [1 2 4];

% 1. y = 0.98 controls (anomalous dispersive regime, M(k0) > 0)
y098 = 0.98;
coeff098 = alpha_lit * (f0 ^ (1 - y098));
controls_098 = cell(1, numel(dt_factors));
for k = 1:numel(dt_factors)
    one = run_one_kwave_case(f0, coeff098, y098, '', 1, c, rho, dt_factors(k));
    controls_098{k} = struct( ...
        'dt_factor', dt_factors(k), ...
        'dt_s', one.dt_s, ...
        'Nt', one.Nt, ...
        'field_status', one.field_status, ...
        'max_abs_pressure_Pa', one.max_abs_pressure_Pa, ...
        'attenuation_peak_dB_cm', one.attenuation_dB_cm, ...
        'relative_error_peak_percent', 100 * (one.attenuation_dB_cm - target_f0) / target_f0, ...
        'R2_peak', one.fit_R2, ...
        'attenuation_spectral_dB_cm', one.attenuation_spectral_dB_cm, ...
        'relative_error_spectral_percent', 100 * (one.attenuation_spectral_dB_cm - target_f0) / target_f0, ...
        'R2_spectral', one.fit_R2_spectral, ...
        'spectral_frequency_MHz', one.spectral_frequency_MHz, ...
        'measured_phase_speed_m_s', one.measured_phase_speed_m_s, ...
        'analytical_pde_attenuation_dB_cm', one.analytical_pde_attenuation_dB_cm, ...
        'analytical_phase_speed_m_s', one.analytical_phase_speed_m_s, ...
        'stiffness_M_k0', one.stiffness_M_k0, ...
        'distances_m', one.distances_m);
end

% 2. y = 0.99 controls (Hadamard ill-posed regime, M(k0) < 0)
y099 = 0.99;
coeff099 = alpha_lit * (f0 ^ (1 - y099));
controls_099 = cell(1, numel(dt_factors));
for k = 1:numel(dt_factors)
    one = run_one_kwave_case(f0, coeff099, y099, '', 1, c, rho, dt_factors(k));
    controls_099{k} = struct( ...
        'dt_factor', dt_factors(k), ...
        'dt_s', one.dt_s, ...
        'Nt', one.Nt, ...
        'field_status', one.field_status, ...
        'max_abs_pressure_Pa', one.max_abs_pressure_Pa, ...
        'p_max_pos_first_sensor_Pa', one.p_max_pos(1), ...
        'p_min_neg_first_sensor_Pa', one.p_min_neg(1), ...
        'stiffness_M_k0', one.stiffness_M_k0);
end

result = struct( ...
    'case', 'homogeneous_1D_interior_source_timestep_and_estimator_controls', ...
    'constants', struct( ...
        'f0_MHz', f0, ...
        'alpha_lit_dB_cm_MHz', alpha_lit, ...
        'target_dB_cm_at_f0', target_f0, ...
        'alpha_coeff_y098', coeff098, ...
        'alpha_power', y098, ...
        'source_idx_grid', 35, ...
        'pml_size_grid', 20, ...
        't_end_s', 180e-6), ...
    'controls', [controls_098{:}], ...
    'controls_y099_hadamard_blowup', [controls_099{:}]);

out_dir = fileparts(output_path);
if ~isempty(out_dir) && ~isfolder(out_dir), mkdir(out_dir); end
fid = fopen(output_path, 'w');
assert(fid >= 0, 'Cannot open output path: %s', output_path);
cleanup_obj = onCleanup(@() fclose(fid));
fwrite(fid, jsonencode(result, 'PrettyPrint', true), 'char');
end
